// Extracts the state (1 or 0) of a single cell at a specific (x, y) coordinate
int get_cell_state(int grid_height_rows, int grid_width_cells, unsigned int grid[grid_height_rows][grid_width_cells], int x, int y) { 
    // Divide x by 32 to find which integer (word) contains our cell
    int column_word_index = x / 32;
    // Use modulo 32 to find the exact bit position inside that specific integer   
    int cell_bit_offset = x % 32;    
    // Shift the word right so our target bit is at the 1s place, then mask it with 1 to isolate it
    return (grid[y][column_word_index] >> cell_bit_offset) & 1U;
}

// Initial seed for the random number generator
unsigned int seed = 12345u;

// A simple number generator to generate random 1s or 0s
int random01(void) {
    //Multiply by a large number and add an offset to scramble the seed
    seed = seed * 1103515245u + 12345u;
    // Shift right by 31 to grab the most significant bit, masking it to return strictly 0 or 1
    return (seed >> 31) & 1;
}

// Randomly populates the 32-bit array with 1s and 0s
void populateGrid(int grid_w, int grid_height_rows, int grid_width_cells, unsigned int grid[grid_height_rows][grid_width_cells], char fill) {
    // Loop through every vertical row in the grid
    for (int y = 0; y < grid_height_rows; y++) {
        // Loop through every 32-bit word in the current row
        for (int w = 0; w < grid_width_cells; w++) {
            // Initialize the entire word to 0 (all cells dead) before populating
            grid[y][w] = 0;
        }
        // Loop through the individual cells, explicitly skipping the very first (0) and last (grid_w - 1) columns
        if(fill){

            for (int x = 1; x < grid_w - 1; x++) {
                //if random01() returns 1, we make the cell alive
                if (random01()) {
                    // Find which 32-bit chunk this x-coordinate belongs to
                    int column_word_index = x / 32;
                    // Find the exact bit position within that chunk
                    int cell_bit_offset = x % 32;
                    // Shift a 1 to the correct bit position and use bitwise OR to set it without overwriting neighbors
                    grid[y][column_word_index] |= (1U << cell_bit_offset);
                }
            }
        }

    }
}

// Computes the next state for 32 cells simultaneously using parallel bitwise logic
static inline unsigned int compute_next_32(unsigned int top_L, unsigned int top_C, unsigned int top_R, unsigned int mid_L, unsigned int mid_C, unsigned int mid_R, unsigned int bot_L, unsigned int bot_C, unsigned int bot_R) {
    // Variables to hold the 1s (S0) and 2s (S1) places of the sum for each row
    unsigned int top_sum_bit1, top_sum_bit0, mid_S1, mid_S0, bot_S1, bot_S0;

    // 1. Sum the 3 rows horizontally
    // XOR acts as addition without carry for the 1s place of the top row
    top_sum_bit0 = top_L ^ top_C ^ top_R;
    // Calculate the carry (2s place) for the top row using bitwise AND combinations
    top_sum_bit1 = (top_L & top_C) | (top_L & top_R) | (top_C & top_R);

    // Mid row only sums left and right (excluding the center cell itself from the neighbor count)
    mid_S0 = mid_L ^ mid_R;  
    // Carry bit for the mid row
    mid_S1 = mid_L & mid_R;

    // XOR addition for the 1s place of the bottom row
    bot_S0 = bot_L ^ bot_C ^ bot_R;
    // Calculate the carry (2s place) for the bottom row
    bot_S1 = (bot_L & bot_C) | (bot_L & bot_R) | (bot_C & bot_R);

    // 2. Add Top + Bot counts together
    // Combine the 1s places of top and bottom; this becomes the new 1s place (top_bot_sum_b0)
    unsigned int top_bot_sum_b0 = top_sum_bit0 ^ bot_S0;
    // Calculate the carry generated by adding the two 1s places
    unsigned int carry_bit_1  = top_sum_bit0 & bot_S0;
    
    // Combine the 2s places (top_sum_bit1, bot_S1) plus the carry from the 1s place (carry_bit_1)
    unsigned int top_bot_sum_b1 = top_sum_bit1 ^ bot_S1 ^ carry_bit_1;
    // Calculate the new carry (4s place) generated by adding the 2s places
    unsigned int top_bot_sum_b2 = (top_sum_bit1 & bot_S1) | (top_sum_bit1 & carry_bit_1) | (bot_S1 & carry_bit_1);

    // 3. Add Mid row count to (Top + Bot) count to get final neighbor totals (neighbor_count_b0-neighbor_count_b3)
    // Final 1s place: XOR the Top/Bot 1s place with the Mid 1s place
    unsigned int neighbor_count_b0 = top_bot_sum_b0 ^ mid_S0;
    // Carry from adding the 1s places
    unsigned int carry_bit_1_2 = top_bot_sum_b0 & mid_S0;

    // Final 2s place: XOR the Top/Bot 2s place, Mid 2s place, and the new carry
    unsigned int neighbor_count_b1 = top_bot_sum_b1 ^ mid_S1 ^ carry_bit_1_2;
    // Carry generated from adding the 2s places
    unsigned int carry_bit_2 = (top_bot_sum_b1 & mid_S1) | (top_bot_sum_b1 & carry_bit_1_2) | (mid_S1 & carry_bit_1_2);

    // Final 4s place: XOR the Top/Bot 4s place with the carry from the 2s place
    unsigned int neighbor_count_b2 = top_bot_sum_b2 ^ carry_bit_2;
    // Final 8s place: AND the 4s place and carry (only happens if 8 neighbors exist)
    unsigned int neighbor_count_b3 = top_bot_sum_b2 & carry_bit_2;

    // 4. Conway's Rules
    // Survive if 2 or 3 neighbors (binary 0010 or 0011). Born if exactly 3 (0011).
    // (~neighbor_count_b3) & (~neighbor_count_b2) ensures neighbors < 4. neighbor_count_b1 ensures neighbors >= 2. 
    // (neighbor_count_b0 | mid_C) means either it has 3 neighbors (neighbor_count_b0 is 1) OR it has 2 and is currently alive (mid_C is 1).
    return (~neighbor_count_b3) & (~neighbor_count_b2) & neighbor_count_b1 & (neighbor_count_b0 | mid_C);
}

// Main simulation loop: Reads the current grid (current_state) and writes to the next buffer (next_state). 
// 1. Calculates wrap-around (toroidal) coordinates for the top and bottom rows.
// 2. Extracts the left and right neighbor words, wrapping horizontally at the edges.
// 3. Shifts bits across the 32-bit word boundaries so all 8 neighbors align perfectly for the parallel bitwise calculation.
void step_simulation_32(int grid_height_rows, int grid_width_cells, unsigned int current_state[grid_height_rows][grid_width_cells], unsigned int next_state[grid_height_rows][grid_width_cells]) {
    // Loop through every row in the grid
    for (int y = 0; y < grid_height_rows; y++) {
        // Calculate toroidal (wrap-around) y-coordinate for the row above
        int y_top = (y == 0) ? grid_height_rows - 1 : y - 1;
        // Calculate toroidal y-coordinate for the row below
        int y_bot = (y == grid_height_rows - 1) ? 0 : y + 1;

        // Loop through each 32-bit word in the current row
        for (int x = 0; x < grid_width_cells; x++) {
            // Grab the center 32-bit blocks for top, mid, and bottom rows
            unsigned int t_C = current_state[y_top][x];
            unsigned int m_C = current_state[y][x];
            unsigned int b_C = current_state[y_bot][x];

            // Grab the left neighboring 32-bit blocks, wrapping around if at the left edge (x=0)
            // Shift left and pull in the boundary bit from the neighboring word (31st bit of the left neighbor)
            unsigned int left_word_t = (x > 0) ? current_state[y_top][x-1] : current_state[y_top][grid_width_cells-1];
            unsigned int left_word_m = (x > 0) ? current_state[y][x-1]     : current_state[y][grid_width_cells-1];
            unsigned int left_word_b = (x > 0) ? current_state[y_bot][x-1] : current_state[y_bot][grid_width_cells-1];

            // Shift center left by 1 to represent right neighbors, and pull in the rightmost bit (bit 31) from the left word
            unsigned int t_L = (t_C << 1) | (left_word_t >> 31);
            unsigned int m_L = (m_C << 1) | (left_word_m >> 31);
            unsigned int b_L = (b_C << 1) | (left_word_b >> 31);

            // Grab the right neighboring 32-bit blocks, wrapping around if at the right edge
            // Shift right and pull in the boundary bit from the neighboring word
            unsigned int right_word_t = (x < grid_width_cells-1) ? current_state[y_top][x+1] : current_state[y_top][0];
            unsigned int right_word_m = (x < grid_width_cells-1) ? current_state[y][x+1]     : current_state[y][0];
            unsigned int right_word_b = (x < grid_width_cells-1) ? current_state[y_bot][x+1] : current_state[y_bot][0];

            // Shift center right by 1 to represent left neighbors, and pull in the leftmost bit (bit 0, shifted to 31) from the right word
            unsigned int t_R = (t_C >> 1) | (right_word_t << 31);
            unsigned int m_R = (m_C >> 1) | (right_word_m << 31);
            unsigned int b_R = (b_C >> 1) | (right_word_b << 31);

            // Pass all aligned 32-bit chunks into the logic function and store the result in the destination grid
            next_state[y][x] = compute_next_32(t_L, t_C, t_R, m_L, m_C, m_R, b_L, b_C, b_R);
        }
    }
}